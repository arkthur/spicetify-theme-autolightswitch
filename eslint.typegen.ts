import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';

import type { Linter } from 'eslint';
import { flatConfigsToPlugins, pluginsToRulesDTS } from 'eslint-typegen/core';

export interface TypedPlugin {
  /** Plugin name as registered in the config's `plugins` (the rule prefix). */
  name: string;
  /**
   * TS type expression for the plugin's typed rule modules, e.g.
   * `typeof import('eslint-plugin-import-x').rules`.
   */
  rulesType: string;
}

export interface TypegenOptions {
  dtsPath?: string;
  /**
   * Plugins whose rule options come from their own typed rule modules instead
   * of the JSON schema eslint-typegen infers from (which some plugins leave
   * loose, e.g. import-x's `groups` is just `unknown[]`).
   */
  typedPlugins?: readonly TypedPlugin[];
}

const HASH_PATTERN = /\/\* typegen-hash: (\S+) \*\//;

function typedRulesDTS(
  typedPlugins: readonly TypedPlugin[],
  plugins: Awaited<ReturnType<typeof flatConfigsToPlugins>>
) {
  const entries = typedPlugins.flatMap(({ name, rulesType }) => {
    const plugin = plugins[name];

    if (!plugin) {
      throw new Error(`Typed plugin "${name}" is not registered in the config`);
    }

    return Object.keys(plugin.rules ?? {})
      .sort()
      .map(
        (rule) =>
          `  '${name}/${rule}'?: Linter.RuleEntry<OptionsOf<(${rulesType})['${rule}']>>`
      );
  });

  return [
    "type OptionsOf<Rule> = import('@typescript-eslint/utils/eslint-utils').InferOptionsTypeFromRule<Rule>",
    '',
    'export interface TypedRuleOptions {',
    ...entries,
    '}'
  ];
}

/**
 * Generates `RuleOptions` (rule names and options for every plugin in the
 * config) and returns the configs untouched. Like `eslint-typegen`, but plugins
 * in `typedPlugins` get their options from their own typed rule modules.
 */
export async function typegen(
  configs: Promise<Linter.Config[]> | Linter.Config[],
  { dtsPath = 'eslint-typegen.d.ts', typedPlugins = [] }: TypegenOptions = {}
) {
  const resolved = await configs;
  // Deprecated with no replacement; eslint-typegen reads core rules the same way.
  // eslint-disable-next-line @typescript-eslint/no-deprecated
  const { builtinRules } = await import('eslint/use-at-your-own-risk');
  const plugins = await flatConfigsToPlugins([
    { plugins: { '': { rules: Object.fromEntries(builtinRules) } } },
    ...resolved
  ]);

  const hash = createHash('sha256')
    .update(
      JSON.stringify([
        Object.entries(plugins)
          .map(([name, plugin]) => [
            name,
            plugin.meta?.name,
            plugin.meta?.version
          ])
          .sort(),
        typedPlugins
      ])
    )
    .digest('base64url');
  const current =
    existsSync(dtsPath) ?
      HASH_PATTERN.exec(await readFile(dtsPath, 'utf-8'))?.[1]
    : undefined;

  if (current === hash) {
    return resolved;
  }

  const typedNames = new Set(typedPlugins.map(({ name }) => name));
  const schemaPlugins = Object.fromEntries(
    Object.entries(plugins).filter(([name]) => !typedNames.has(name))
  );

  await writeFile(
    dtsPath,
    [
      '/* This file is generated by eslint.typegen.ts */',
      `/* typegen-hash: ${hash} */`,
      '',
      await pluginsToRulesDTS(schemaPlugins, {
        exportTypeName: 'SchemaRuleOptions',
        includeAugmentation: false
      }),
      '',
      ...typedRulesDTS(typedPlugins, plugins),
      '',
      'export interface RuleOptions extends SchemaRuleOptions, TypedRuleOptions {}',
      ''
    ].join('\n'),
    'utf-8'
  );

  return resolved;
}
